"""Builds every generated model (or a subset) and exports .glb files into the Godot project.

Run through tools/build_assets.py, or directly:
  blender --background --factory-startup --python art/blender/build_all.py -- [--only id1,id2] [--list]

Each asset module exposes ASSETS = [{"id", "category", "build", "animations"?}]. Output goes to
assets/models/<category>/<id>.glb. If art/manual/<id>.blend exists, that file is exported instead
(manual override, same export settings).
"""
import os
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from lib import cli, export, palette  # noqa: E402


def collect():
    import importlib
    assets = []
    for pkg in ("props", "characters", "gear", "fx", "env"):
        d = os.path.join(HERE, pkg)
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if fn.endswith(".py") and not fn.startswith("_"):
                mod = importlib.import_module("%s.%s" % (pkg, fn[:-3]))
                assets.extend(getattr(mod, "ASSETS", []))
                if hasattr(mod, "assets"):
                    assets.extend(mod.assets())
    ids = [a["id"] for a in assets]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit("duplicate asset ids: %s" % sorted(dup))
    return assets


def _env_metadata(a):
    """Bounds (Godot axes: x, y up, z = -Blender y), triangles and open (non-manifold) edges above the ground."""
    import bmesh
    import bpy
    from mathutils import Vector
    lo = Vector((1e9, 1e9, 1e9))
    hi = Vector((-1e9, -1e9, -1e9))
    tris = 0
    open_edges = 0
    for ob in bpy.context.scene.objects:
        if ob.type != "MESH":
            continue
        bm = bmesh.new()
        bm.from_mesh(ob.data)
        bm.transform(ob.matrix_world)
        for v in bm.verts:
            g = Vector((v.co.x, v.co.z, -v.co.y))
            lo = Vector(map(min, lo, g))
            hi = Vector(map(max, hi, g))
        tris += sum(len(f.verts) - 2 for f in bm.faces)
        for e in bm.edges:
            if e.is_boundary and min(v.co.z for v in e.verts) > 0.02 and not a.get("meta", {}).get("open_ok", False):
                open_edges += 1
        bm.free()
    meta = {"aabb": [round(x, 4) for x in (*lo, *hi)], "tris": tris, "open_edges": open_edges}
    meta.update(a.get("meta", {}))
    return meta


def _write_env_metadata(new):
    import json
    path = os.path.join(palette.ROOT, "data", "art", "env_modules.json")
    data = {"_doc": "GENERATED by art/blender/build_all.py: environment module bounds (Godot axes, tiles), "
                    "triangles, open edges and role. Read by the environment builder, test and checks.",
            "modules": {}}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            data["modules"] = json.load(f).get("modules", {})
    data["modules"].update(new)
    data["modules"] = dict(sorted(data["modules"].items()))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=1)
        f.write("\n")


def main():
    assets = collect()
    if cli.flag("--list"):
        for a in assets:
            print("ASSET", a["category"], a["id"])
        return
    only = cli.opt("--only")
    if only:
        want = set(only.split(","))
        missing = want - {a["id"] for a in assets}
        if missing:
            raise SystemExit("unknown asset ids: %s" % sorted(missing))
        assets = [a for a in assets if a["id"] in want]
    t0 = time.time()
    failed = []
    env_meta = {}
    for a in assets:
        out = os.path.join(palette.ROOT, "assets", "models", a["category"], a["id"] + ".glb")
        manual = os.path.join(palette.ROOT, "art", "manual", a["id"] + ".blend")
        try:
            if os.path.exists(manual):
                export.export_manual(manual, out, a.get("animations", False))
                print("BUILT", a["id"], "(manual override)")
                continue
            export.reset_scene()
            palette.use("env" if a["category"] == "env" else "main")
            a["build"]()
            if a["category"] == "env":
                env_meta[a["id"]] = _env_metadata(a)
            export.export_glb(out, animations=a.get("animations", False))
            print("BUILT", a["id"])
        except Exception:  # keep going, report at the end
            traceback.print_exc()
            failed.append(a["id"])
    if env_meta:
        _write_env_metadata(env_meta)
    print("DONE %d assets in %.1fs, %d failed" % (len(assets), time.time() - t0, len(failed)))
    if failed:
        print("FAILED", ",".join(failed))
        sys.exit(1)


main()
